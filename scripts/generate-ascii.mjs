import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const RAMP = " .:-=+*#%@";

async function imageToAscii(inputPath, width, height) {
  const { data, info } = await sharp(inputPath)
    .resize(width, height, { fit: "cover" })
    .grayscale()
    .clahe({ width: 8, height: 8, maxSlope: 4 })
    .normalize()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const lines = [];
  for (let y = 0; y < info.height; y++) {
    let row = "";
    for (let x = 0; x < info.width; x++) {
      const idx = y * info.width + x;
      const lum = data[idx] / 255;
      // Circular vignette so portrait blends into the terminal background
      const nx = (x / (info.width - 1)) * 2 - 1;
      const ny = (y / (info.height - 1)) * 2 - 1;
      const dist = Math.sqrt(nx * nx + ny * ny);
      const vignette = Math.max(0, 1 - Math.pow(dist / 1.05, 3.2));
      const adjusted = Math.min(1, Math.pow(lum, 0.7) * 1.2) * vignette;
      const charIdx = Math.min(
        RAMP.length - 1,
        Math.max(0, Math.floor(adjusted * (RAMP.length - 1)))
      );
      row += RAMP[charIdx];
    }
    lines.push(row);
  }
  return lines;
}

async function main() {
  const root = process.cwd();
  const inputPath = path.join(root, "public", "avatar.png");
  const outPath = path.join(root, "data", "ascii-portrait.ts");

  const desktopLines = await imageToAscii(inputPath, 68, 34);
  const mobileLines = await imageToAscii(inputPath, 44, 22);

  const fileContent = `// Auto-generated by scripts/generate-ascii.mjs from public/avatar.png
// Do not edit manually — run: node scripts/generate-ascii.mjs

export const asciiPortraitDesktop: readonly string[] = ${JSON.stringify(
    desktopLines,
    null,
    2
  )};

export const asciiPortraitMobile: readonly string[] = ${JSON.stringify(
    mobileLines,
    null,
    2
  )};
`;

  await fs.writeFile(outPath, fileContent, "utf8");
  console.log("Generated data/ascii-portrait.ts successfully.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
